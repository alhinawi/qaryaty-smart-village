// ─── Writes supabase/seed.sql from the sample data in src/data
// Run: pnpm seed:sql   (then paste supabase/seed.sql into the Supabase SQL Editor)
import { writeFileSync } from 'node:fs';
import { SERVICES } from '../src/data/services';
import { SHOPS } from '../src/data/shops';
import { PROVIDERS } from '../src/data/providers';

type Value = string | number | boolean | null | undefined | string[] | object;

function sql(value: Value): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value) && value.every((v) => typeof v === 'string'))
    return `array[${value.map(sql).join(', ')}]::text[]`;
  if (typeof value === 'object') return `${sql(JSON.stringify(value))}::jsonb`;
  return `'${value.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, Value>[]): string {
  if (rows.length === 0) return '';
  const columns = Object.keys(rows[0]);
  const values = rows.map((row) => `  (${columns.map((c) => sql(row[c])).join(', ')})`).join(',\n');
  const updates = columns.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ');
  return `insert into public.${table} (${columns.join(', ')}) values\n${values}\non conflict (id) do update set ${updates};\n`;
}

const services = SERVICES.map((s) => ({
  id: s.id,
  cat: s.cat,
  emoji: s.emoji,
  name: s.name,
  description: s.desc,
  time: s.time,
  price: s.price,
  numeric_price: s.numericPrice,
  price_type: s.priceType,
  rating: s.rating,
  badge: s.badge,
  featured: s.featured ?? false,
  subject: s.subject ?? null,
  options: s.options ?? null,
  hidden: s.hidden ?? false,
}));

const shops = SHOPS.map((s) => ({
  id: s.id,
  emoji: s.emoji,
  name: s.name,
  description: s.description,
  open: s.open,
  time: s.time,
  bg_color: s.bgColor,
}));

const providers = PROVIDERS.map((p) => ({
  id: p.id,
  kind: p.kind,
  service_id: p.serviceId,
  name: p.name,
  gender: p.gender,
  photo: p.photo || null,
  subject: p.subject ?? null,
  stages: p.stages ?? null,
  specialty: p.specialty ?? null,
  role: p.role ?? null,
  experience_years: p.experienceYears,
  rating: p.rating,
  reviews: p.reviews,
  price: p.price,
  numeric_price: p.numericPrice,
  price_type: p.priceType,
  area: p.area,
  bio: p.bio,
  modes: p.modes,
  active: p.active,
}));

const out = [
  '-- Generated by scripts/make-seed.ts from src/data. Do not edit by hand.',
  '-- Run after schema.sql. Safe to run again: existing rows are updated.',
  '',
  insert('services', services),
  insert('shops', shops),
  insert('providers', providers),
].join('\n');

// Run from the project root (pnpm seed:sql does)
writeFileSync('supabase/seed.sql', out);
console.log(`supabase/seed.sql: ${services.length} services, ${shops.length} shops, ${providers.length} providers`);
