// ─── Writes supabase/seed.sql from the sample data in src/data
// Review-only generation: never run generated SQL on production without separate approval.
import { writeFileSync } from 'node:fs';
import { SERVICES } from '../src/data/services';
import { SHOPS } from '../src/data/shops';
import { DEVELOPER_TEACHER_IDS, PROVIDERS } from '../src/data/providers';
import { CATALOG_BY_KIND, MENUS } from '../src/data/catalog';
import type { Product } from '../src/types';

type Value = string | number | boolean | null | undefined | string[] | object;

function sql(value: Value): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value) && value.every((v) => typeof v === 'string'))
    return `array[${value.map(sql).join(', ')}]::text[]`;
  if (typeof value === 'object') return `${sql(JSON.stringify(value))}::jsonb`;
  return `'${value.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, Value>[]): string {
  if (rows.length === 0) return '';
  const columns = Object.keys(rows[0]);
  const values = rows.map((row) => `  (${columns.map((c) => sql(row[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${values}\non conflict (id) do nothing;\n`;
}

const services = SERVICES.map((s) => ({
  id: s.id,
  is_demo: true,
  cat: s.cat,
  emoji: s.emoji,
  name: s.name,
  description: s.desc,
  time: s.time,
  price: s.price,
  numeric_price: s.numericPrice,
  price_type: s.priceType,
  rating: s.rating,
  badge: s.badge,
  featured: s.featured ?? false,
  subject: s.subject ?? null,
  options: s.options ?? null,
  hidden: s.hidden ?? false,
  keywords: s.keywords ?? null,
  quantity: s.quantity ?? null,
}));

const shops = SHOPS.map((s) => ({
  id: s.id,
  is_demo: true,
  emoji: s.emoji,
  name: s.name,
  description: s.description,
  open: s.open,
  time: s.time,
  bg_color: s.bgColor,
  kind: s.kind ?? 'other',
  food_types: s.foodTypes ?? [],
  photo: s.photo ?? null,
}));

const providers = PROVIDERS.map((p) => ({
  id: p.id,
  // The developer's own teacher cards are real, not sample data
  is_demo: !(DEVELOPER_TEACHER_IDS as readonly number[]).includes(p.id),
  kind: p.kind,
  service_id: p.serviceId,
  name: p.name,
  gender: p.gender,
  photo: p.photo || null,
  subject: p.subject ?? null,
  stages: p.stages ?? null,
  specialty: p.specialty ?? null,
  role: p.role ?? null,
  experience_years: p.experienceYears,
  rating: p.rating,
  reviews: p.reviews,
  price: p.price,
  numeric_price: p.numericPrice,
  price_type: p.priceType,
  area: p.area,
  village: p.village,
  bio: p.bio,
  modes: p.modes,
  group_price: p.groupPrice ?? null,
  inspection_fee: p.inspectionFee ?? null,
  delivery_fee: p.deliveryFee ?? null,
  groups: p.groups ?? null,
  links: p.links ?? null,
  active: p.active,
}));

// What each kind of shop sells, and each restaurant's menu. The order trigger
// prices cart orders from these rows, so they must match src/data/catalog.ts.
const productRow = (scope: string) => (p: Product, position: number) => ({
  scope,
  product_id: p.id,
  name: p.name,
  price: p.price,
  unit: p.unit,
  step: p.step ?? 1,
  grillable: p.grillable ?? false,
  rx: p.rx ?? false,
  emoji: p.emoji,
  section: p.section ?? '',
  photo: p.photo ?? null,
  position,
});
const products = [
  ...Object.entries(CATALOG_BY_KIND).flatMap(([kind, list]) => (list ?? []).map(productRow(kind))),
  ...Object.entries(MENUS).flatMap(([shopId, list]) => list.map(productRow(`restaurant:${shopId}`))),
];

function insertProducts(rows: ReturnType<ReturnType<typeof productRow>>[]): string {
  const columns = Object.keys(rows[0]) as (keyof (typeof rows)[number])[];
  const values = rows.map((row) => `  (${columns.map((c) => sql(row[c])).join(', ')})`).join(',\n');
  return [
    '-- Existing catalog rows are preserved; no pruning or overwrite.',
    `insert into public.catalog_products (${columns.join(', ')}) values\n${values}\non conflict (scope, product_id) do nothing;\n`,
  ].join('\n');
}

const out = [
  '-- Generated by scripts/make-seed.ts from src/data. Do not edit by hand.',
  '-- REVIEW ONLY. Requires existing is_demo columns on shops/providers/services.',
  '-- No DELETE or UPDATE. Never replaces existing real or legacy rows.',
  '-- Product provenance needs separate reviewed SQL; do not seed a live database.',
  '',
  insert('services', services),
  insert('shops', shops),
  insert('providers', providers),
  insertProducts(products),
].join('\n');

// Run from the project root (pnpm seed:sql does)
writeFileSync('supabase/seed.sql', out);
console.log(`supabase/seed.sql: ${services.length} services, ${shops.length} shops, ${providers.length} providers, ${products.length} products`);
