import json
d=json.load(open('villages.json'))
def q(s): return "'"+s.replace("'","''")+"'"
def n(x): return 'null' if x is None else repr(x)
out=["-- Generated by scripts/villages/build_villages.py + to_sql.py. Do not edit by hand.",
"-- Sources: Wikidata (village in Egypt), GeoNames EG + Arabic alternate names, OpenStreetMap",
"-- (place=village/hamlet/town/city), placed in markaz/governorate with COD-AB Egypt (CAPMAS).",
"-- Re-running replaces the list but keeps which villages are served.",
"begin;",
"create temp table _keep_served on commit drop as select label from public.villages where served;",
"delete from public.villages where id > 0;"]
rows=[]
for i,v in enumerate(d,1):
    rows.append(f"({i},{q(v['name'])},{q(v['markaz'])},{q(v['governorate'])},{n(v['lat'])},{n(v['lng'])},{q(v['kind'])})")
for j in range(0,len(rows),1000):
    out.append("insert into public.villages (id, name, markaz, governorate, lat, lng, kind) values\n"+",\n".join(rows[j:j+1000])+";")
out+=["update public.villages set served = true where label in (select label from _keep_served);",
"-- منية سندوب، مركز المنصورة - الدقهلية: where Qaryaty delivers today",
"update public.villages set served = true where name = 'منية سندوب' and governorate = 'الدقهلية';",
"-- Old profiles: a full label, or a bare name that only one village in Egypt has, gets its id.",
"update public.profiles p set village_id = v.id from public.villages v",
"  where p.village_id is null and p.village is not null and v.label = btrim(p.village);",
"update public.profiles p set village_id = u.id from (",
"  select search_key, min(id) as id from public.villages group by search_key having count(*) = 1",
") u where p.village_id is null and p.village is not null and u.search_key = public.ar_normalize(p.village);",
"commit;",
"analyze public.villages;"]
open('/home/sprite/qv-villages/supabase/migrations/20261106160100_villages_data.sql','w').write("\n".join(out)+"\n")
print(len(d))
